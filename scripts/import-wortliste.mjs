// Imports the Goethe A1 Wortliste into the extended wordlist.
//
// Input: a TAB-separated file (default: data/goethe-a1.tsv) with a header row.
// Columns (header names, order-independent):
//   category   pos   article   lemma   plural   ru   en
//     - category : grouping id (e.g. "places"); optional, defaults to "a1list"
//     - pos      : noun | verb | adjective | adverb | preposition | pronoun
//                  | conjunction | numeral | phrase
//     - article  : der | die | das  (nouns only; maps to gender m/f/n)
//     - lemma    : German dictionary form (required)
//     - plural   : full plural form (nouns; optional)
//     - ru / en  : translations (optional now, fill later)
//
// Output: src/content/wordlist/imported.ts  (auto-generated; do not hand-edit)
//
// Run: node scripts/import-wortliste.mjs [path/to/file.tsv]

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const inputPath = resolve(root, process.argv[2] ?? "data/goethe-a1.tsv");
const outputPath = resolve(root, "src/content/wordlist/imported.ts");

const GENDER = { der: "m", die: "f", das: "n" };

function slug(s) {
  return s
    .toLowerCase()
    .replace(/ä/g, "a").replace(/ö/g, "o").replace(/ü/g, "u").replace(/ß/g, "ss")
    .replace(/[^a-z0-9]+/g, "");
}

function jstr(s) {
  return JSON.stringify(s ?? "");
}

const raw = readFileSync(inputPath, "utf8");
const lines = raw.split(/\r?\n/).filter((l) => l.trim() && !l.trim().startsWith("#"));
if (lines.length < 2) throw new Error("Input has no data rows.");

const header = lines[0].split("\t").map((h) => h.trim().toLowerCase());
const col = (name) => header.indexOf(name);
const idx = {
  category: col("category"), pos: col("pos"), article: col("article"),
  lemma: col("lemma"), plural: col("plural"), ru: col("ru"), en: col("en"), uk: col("uk"),
};
if (idx.lemma < 0 || idx.pos < 0) throw new Error('Header must include at least "pos" and "lemma".');

const seen = new Set();
const entries = [];
let skipped = 0;

for (const line of lines.slice(1)) {
  const c = line.split("\t");
  const get = (i) => (i >= 0 ? (c[i] ?? "").trim() : "");
  const lemma = get(idx.lemma);
  if (!lemma) { skipped++; continue; }

  const pos = (get(idx.pos) || "noun").toLowerCase();
  const id = `g-${slug(lemma)}`;
  if (seen.has(id)) { skipped++; continue; } // de-dupe within the import
  seen.add(id);

  const category = get(idx.category) || "a1list";
  const ru = get(idx.ru) || lemma;
  const en = get(idx.en) || lemma;
  const uk = get(idx.uk); // optional Ukrainian translation
  const translation = uk
    ? `{ ru: ${jstr(ru)}, en: ${jstr(en)}, uk: ${jstr(uk)} }`
    : `{ ru: ${jstr(ru)}, en: ${jstr(en)} }`;

  const parts = [
    `id: ${jstr(id)}`,
    `level: "A1"`,
    `tier: "extended"`,
    `theme: ${jstr(category)}`,
    `lemma: ${jstr(lemma)}`,
    `pos: ${jstr(pos)}`,
    `translation: ${translation}`,
  ];

  if (pos === "noun") {
    const gender = GENDER[get(idx.article).toLowerCase()];
    if (!gender) { console.warn(`! noun without valid article: "${lemma}" — defaulting to n`); }
    const plural = get(idx.plural);
    const nounFields = `gender: ${jstr(gender || "n")}` + (plural ? `, plural: ${jstr(plural)}` : "");
    parts.push(`noun: { ${nounFields} }`);
  }

  parts.push(`examples: []`);
  entries.push(`  { ${parts.join(", ")} },`);
}

const out = `import type { Word } from "@/lib/types";

// AUTO-GENERATED by scripts/import-wortliste.mjs — do not edit by hand.
// Source: Goethe-Zertifikat A1 Wortliste. ${entries.length} entries.
export const imported: Word[] = [
${entries.join("\n")}
];
`;

writeFileSync(outputPath, out, "utf8");
console.log(`✓ Imported ${entries.length} words → ${outputPath}` + (skipped ? ` (${skipped} skipped)` : ""));
